const lines = csvData.split('\n').map(l => l.trim()).filter(l => l);
const products = JSON.parse(fs.readFileSync(productsPath, 'utf8'));

for (let i = 1; i < lines.length; i++) {
  const parts = lines[i].split(',');
  if (parts.length < 9) continue;
  
  const name = parts[0].trim();
  let stock = parseInt(parts[8].trim(), 10);
  if (isNaN(stock)) stock = 0;
  
  if (!name) continue;

  const prod = products.find(p => p.name.trim() === name.trim());
  if (prod) {
    prod.stock = stock;
    console.log(`Updated ${name} stock to ${stock}`);
  } else {
    console.log(`Product not found in JSON: ${name}`);
  }
}

fs.writeFileSync(productsPath, JSON.stringify(products, null, 2));
